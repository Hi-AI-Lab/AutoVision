#!/usr/bin/env python3
"""Design-anchor guard: every design/H id must be anchored by a test (H4-3).

Scans ``src/``, ``tests/`` and ``docs/`` for the design identifiers used by
the architecture docs and the hardening plan:

- ``D<digits>[a-z]``         — design-doc decisions (``D7``, ``D23a``),
- ``H<digits>-<digits>[a-z]`` — hardening-plan items (``H1-2``, ``H3-3b``).

Rule: every id referenced from ``src/`` or ``docs/`` (docstring, comment or
string) must be referenced by at least one ``tests/`` file — in a docstring
or comment — otherwise the id is listed as missing and the run exits 1.
This is the intent->test anchor of hardening plan §3.5: a design claim no
test names is treated as not implemented.

The id grammar is deliberately conservative (word boundaries plus context
checks) so hex literals (``0x1D5``), version numbers (``v0.6.1``),
chemistry (``H2O`` / ``D2O``) and snake_case identifiers never create
phantom ids: uppercase ``D``/``H`` prefixes only, a digit right after the
prefix, and no alphanumeric or underscore neighbour.

Known, time-boxed gaps live in ``scripts/design_anchor_allowlist.toml``
(one ``[<id>]`` table per entry, with ``reason`` and ``expires`` — a UTC
``YYYY-MM-DD`` date). An expired entry fails the run, and an entry whose
id is no longer missing fails too so the table cannot rot — the same
policy as ``provenance_allowlist.txt`` in ``scripts/check_provenance.py``.
``--write-allowlist`` regenerates the table from the current missing set:
surviving entries keep their reason/expiry, new entries default to
today + 90 days.

CI hook: the ``lint`` job in ``.github/workflows/ci.yml``.

Usage:
    python scripts/check_design_anchors.py
    python scripts/check_design_anchors.py --write-allowlist
"""

from __future__ import annotations

import argparse
import ast
import io
import re
import sys
import tokenize
from dataclasses import dataclass
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCAN_ROOTS = ("src", "tests", "docs")
ALLOWLIST_PATH = REPO_ROOT / "scripts" / "design_anchor_allowlist.toml"

_SKIP_DIRS = frozenset({"__pycache__", ".git", ".venv", "node_modules"})
_TEXT_SUFFIXES = frozenset({".py", ".md"})

#: Exemption lifetime for entries generated by ``--write-allowlist``.
DEFAULT_TTL_DAYS = 90
DEFAULT_REASON = "anchor backfill pending (generated by --write-allowlist)"
_MAX_LOCATION_HINTS = 3

#: ``D<digits>[a-z]`` / ``H<digits>-<digits>[a-z]`` with word boundaries.
#: The lookarounds exclude alphanumeric and underscore neighbours, so
#: ``0x1D5`` (hex), ``v0.6.1`` (version), ``H2O``/``D2O`` (chemistry),
#: ``TestD1aWeightsGate`` (identifier fragment) never match.
ID_PATTERN = re.compile(
    r"(?<![A-Za-z0-9_])"
    r"(D\d+[a-z]?|H\d+-\d+[a-z]?)"
    r"(?![A-Za-z0-9_])"
)


@dataclass(frozen=True)
class Reference:
    """One ``file:line`` location where an id is referenced."""

    path: str
    line: int


@dataclass(frozen=True)
class AllowlistEntry:
    """One time-boxed exemption for a not-yet-anchored design id."""

    anchor: str
    reason: str
    expires: date


def extract_ids(text: str) -> set[str]:
    """All design ids in ``text`` (grammar-validated, see ``ID_PATTERN``)."""
    return set(ID_PATTERN.findall(text))


def _rel_path(path: Path) -> str:
    """Repo-relative POSIX path (falls back to absolute outside the repo)."""
    try:
        return path.relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def _iter_text_files() -> list[Path]:
    """All scanned text files (``.py``/``.md`` under src/tests/docs)."""
    files: list[Path] = []
    for root_name in SCAN_ROOTS:
        base = REPO_ROOT / root_name
        if not base.is_dir():
            continue
        files.extend(
            path
            for path in sorted(base.rglob("*"))
            if path.is_file()
            and path.suffix in _TEXT_SUFFIXES
            and not _SKIP_DIRS.intersection(path.parts)
        )
    return files


def _anchor_sort_key(anchor: str) -> tuple[str, int, int, str]:
    """Natural order: prefix, main number, sub number, letter suffix."""
    match = re.fullmatch(r"([DH])(\d+)(?:-(\d+))?([a-z]?)", anchor)
    if match is None:  # pragma: no cover - ID_PATTERN guarantees the shape
        return (anchor, 0, 0, "")
    prefix, main, sub, suffix = match.groups()
    return (prefix, int(main), int(sub or 0), suffix)


def collect_required_ids() -> dict[str, list[Reference]]:
    """Ids referenced from ``src/``/``docs/`` -> their reference locations.

    Ids appearing only in ``tests/`` (or anywhere else) impose no
    requirement: the rule anchors designs that src or docs claim.
    """
    required: dict[str, list[Reference]] = {}
    for path in _iter_text_files():
        rel = _rel_path(path)
        if rel.partition("/")[0] == "tests":
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for line_number, line in enumerate(text.splitlines(), start=1):
            for anchor in extract_ids(line):
                required.setdefault(anchor, []).append(
                    Reference(rel, line_number)
                )
    return required


def _test_file_reference_ids(path: Path) -> set[str]:
    """Ids named in one test file's docstrings and comments (H4-3 scope)."""
    try:
        source = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return set()
    try:
        tree = ast.parse(source, filename=str(path))
    except SyntaxError:
        # An unparsable test file is a different bug; scanning raw text
        # here stays lenient about anchors instead of inventing gaps.
        return extract_ids(source)
    ids: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(
            node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
        ):
            docstring = ast.get_docstring(node)
            if docstring:
                ids |= extract_ids(docstring)
    try:
        for token in tokenize.generate_tokens(io.StringIO(source).readline):
            if token.type == tokenize.COMMENT:
                ids |= extract_ids(token.string)
    except (tokenize.TokenError, IndentationError):  # pragma: no cover
        pass
    return ids


def collect_test_anchors() -> dict[str, set[str]]:
    """Ids referenced in tests (docstrings/comments) -> files naming them."""
    anchored: dict[str, set[str]] = {}
    for path in _iter_text_files():
        rel = _rel_path(path)
        if rel.partition("/")[0] != "tests":
            continue
        for anchor in _test_file_reference_ids(path):
            anchored.setdefault(anchor, set()).add(rel)
    return anchored


def _parse_toml_subset(text: str) -> dict[str, dict[str, object]]:
    """Parse the allowlist's TOML subset: ``[table]`` + ``key = "value"``.

    Only what ``--write-allowlist`` emits (plus tolerant quoting and bare
    dates) is supported; this keeps the check working on Python 3.10,
    where :mod:`tomllib` does not exist.
    """
    data: dict[str, dict[str, object]] = {}
    current: dict[str, object] | None = None
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        header = re.fullmatch(r'\["?([A-Za-z0-9_.-]+)"?\]', line)
        if header:
            current = data.setdefault(header.group(1), {})
            continue
        if current is None:
            continue
        item = re.fullmatch(r"([A-Za-z0-9_-]+)\s*=\s*(.+)", line)
        if item is None:
            continue
        key, raw_value = item.group(1), item.group(2).strip()
        quoted = re.fullmatch(r'"([^"]*)"|\'([^\']*)\'', raw_value)
        if quoted:
            value: object = (
                quoted.group(1) if quoted.group(1) is not None else quoted.group(2)
            )
        else:
            value = raw_value.split("#", 1)[0].strip()
        current[key] = value
    return data


def _coerce_date(value: object) -> date | None:
    """TOML date values (native or ISO string) -> :class:`date`, else None."""
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    if isinstance(value, str):
        try:
            return date.fromisoformat(value)
        except ValueError:
            return None
    return None


def load_allowlist() -> tuple[dict[str, AllowlistEntry], list[str]]:
    """Parse the allowlist; return (entries, structural problems).

    Structural problems (invalid id, missing/non-ISO ``expires``, missing
    ``reason``) are reported to the caller and always fail the run — a
    malformed table must never silently stop exempting.
    """
    if not ALLOWLIST_PATH.exists():
        return {}, []
    text = ALLOWLIST_PATH.read_text(encoding="utf-8")
    try:
        import tomllib
    except ModuleNotFoundError:  # Python 3.10: parse our own subset
        data = _parse_toml_subset(text)
    else:
        data = {
            key: value
            for key, value in tomllib.loads(text).items()
            if isinstance(value, dict)
        }

    entries: dict[str, AllowlistEntry] = {}
    problems: list[str] = []
    for anchor, body in data.items():
        if ID_PATTERN.fullmatch(anchor) is None:
            problems.append(f"allowlist table [{anchor}] is not a design id")
            continue
        reason_value = body.get("reason")
        reason = reason_value if isinstance(reason_value, str) else ""
        if not reason:
            problems.append(f"allowlist entry [{anchor}] is missing a 'reason'")
        expires = _coerce_date(body.get("expires"))
        if expires is None:
            problems.append(
                f"allowlist entry [{anchor}] has a bad/missing 'expires' "
                f"date: {body.get('expires')!r}"
            )
            continue
        entries[anchor] = AllowlistEntry(anchor, reason, expires)
    return entries, problems


def utc_today() -> date:
    """Today's UTC date (allowlist expiry is timezone-independent)."""
    return datetime.now(timezone.utc).date()


def find_missing(
    required: dict[str, list[Reference]],
    anchored: dict[str, set[str]],
) -> list[str]:
    """Required ids no test file references, in natural order."""
    return sorted(
        (anchor for anchor in required if anchor not in anchored),
        key=_anchor_sort_key,
    )


def write_allowlist(
    missing: list[str],
    existing: dict[str, AllowlistEntry],
    today: date,
) -> int:
    """Write the allowlist for ``missing``; return the entry count.

    Surviving entries keep their reason/expiry (regeneration must not
    reset review dates); new entries default to today + 90 days.
    """
    default_expires = today + timedelta(days=DEFAULT_TTL_DAYS)
    lines = [
        "# Design-anchor allowlist (scripts/check_design_anchors.py, H4-3).",
        "# Maintained ONLY via:",
        "#   python scripts/check_design_anchors.py --write-allowlist",
        "# One [<id>] table per not-yet-anchored design id; 'expires' is a",
        "# UTC date bounding the exemption - an expired entry fails the run.",
        "",
    ]
    for anchor in missing:
        old = existing.get(anchor)
        reason = (old.reason if old is not None else DEFAULT_REASON).replace(
            "\\", "\\\\"
        ).replace('"', '\\"')
        expires = old.expires if old is not None else default_expires
        lines.append(f'["{anchor}"]')
        lines.append(f'reason = "{reason}"')
        lines.append(f'expires = "{expires.isoformat()}"')
        lines.append("")
    ALLOWLIST_PATH.write_text("\n".join(lines), encoding="utf-8")
    return len(missing)


def run_check(
    required: dict[str, list[Reference]],
    anchored: dict[str, set[str]],
    allowlist: dict[str, AllowlistEntry],
    structural_problems: list[str],
    today: date,
) -> list[str]:
    """All problems for default mode: unexempted gaps + rotted exemptions."""
    missing = find_missing(required, anchored)
    problems: list[str] = list(structural_problems)
    exempted: set[str] = set()
    for anchor in missing:
        entry = allowlist.get(anchor)
        if entry is None:
            locations = required[anchor][:_MAX_LOCATION_HINTS]
            hints = ", ".join(f"{ref.path}:{ref.line}" for ref in locations)
            extra = len(required[anchor]) - _MAX_LOCATION_HINTS
            suffix = f" (+{extra} more)" if extra > 0 else ""
            problems.append(
                f"no test anchor for {anchor} (referenced at {hints}{suffix})"
            )
        elif entry.expires < today:
            problems.append(
                f"design_anchor_allowlist.toml: entry for {anchor} expired "
                f"on {entry.expires.isoformat()} - anchor the id or "
                "re-justify it with a fresh --write-allowlist run"
            )
        else:
            exempted.add(anchor)
    for anchor in sorted(allowlist, key=_anchor_sort_key):
        if anchor not in missing:
            problems.append(
                f"design_anchor_allowlist.toml: entry for {anchor} is no "
                "longer missing (anchored or unused) - remove it"
            )
    del exempted  # reporting only; the exempted ids simply produce no entry
    return problems


def main(argv: list[str] | None = None) -> int:
    """Check design anchors, or regenerate the allowlist with --write-allowlist."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--write-allowlist",
        action="store_true",
        help="regenerate scripts/design_anchor_allowlist.toml from the "
        "current missing set (surviving entries keep reason/expiry)",
    )
    options = parser.parse_args(argv)

    required = collect_required_ids()
    anchored = collect_test_anchors()
    allowlist, structural_problems = load_allowlist()

    if options.write_allowlist:
        missing = find_missing(required, anchored)
        count = write_allowlist(missing, allowlist, utc_today())
        rel = ALLOWLIST_PATH.relative_to(REPO_ROOT).as_posix()
        print(f"wrote {rel}: {count} entries ({structural_problems or 'valid'})")
        return 0

    problems = run_check(
        required, anchored, allowlist, structural_problems, utc_today()
    )
    if problems:
        print(f"{len(problems)} design-anchor problem(s):")
        for problem in problems:
            print(f"  {problem}")
        print(
            "Anchor each id in a test docstring/comment, or regenerate the "
            "time-boxed allowlist:\n"
            "  python scripts/check_design_anchors.py --write-allowlist"
        )
        return 1
    missing_count = len(find_missing(required, anchored))
    print(
        f"OK: {len(required)} required design id(s); "
        f"{len(required) - missing_count} anchored in tests, "
        f"{missing_count} allowlisted."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
